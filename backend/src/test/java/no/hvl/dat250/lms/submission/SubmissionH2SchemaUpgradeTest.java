package no.hvl.dat250.lms.submission;

import java.sql.DriverManager;
import java.sql.SQLException;
import java.util.UUID;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.datasource.init.ScriptUtils;
import static org.junit.jupiter.api.Assertions.*;

/** Reproduces the old Hibernate-generated H2 submissions schema in an isolated database. */
class SubmissionH2SchemaUpgradeTest {
    @Test
    void manualUpgradePreservesLegacyRowsAndAllowsFileMetadataWithoutPayload() throws Exception {
        try (var connection = DriverManager.getConnection("jdbc:h2:mem:upgrade_" + UUID.randomUUID(), "sa", "")) {
            try (var sql = connection.createStatement()) {
                sql.execute("""
                    CREATE TABLE submissions (
                        late BOOLEAN NOT NULL,
                        content_id BIGINT NOT NULL,
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        submitted_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
                        submitted_by_id BIGINT NOT NULL,
                        payload VARCHAR(10000) NOT NULL,
                        submission_type ENUM ('GIT_URL', 'TEXT') NOT NULL
                    )
                    """);
                sql.execute("""
                    INSERT INTO submissions (content_id, submitted_by_id, submission_type, payload, submitted_at, late)
                    VALUES (10, 20, 'TEXT', 'Original answer', TIMESTAMP WITH TIME ZONE '2026-11-15 12:00:00+00', FALSE),
                           (10, 20, 'GIT_URL', 'https://example.com/repo', TIMESTAMP WITH TIME ZONE '2026-11-15 13:00:00+00', TRUE)
                    """);
                assertThrows(SQLException.class, () -> sql.execute("""
                    INSERT INTO submissions (content_id, submitted_by_id, submission_type, payload, submitted_at, late)
                    VALUES (10, 20, 'FILE', 'key', CURRENT_TIMESTAMP, FALSE)
                    """));
                assertThrows(SQLException.class, () -> sql.execute("""
                    INSERT INTO submissions (content_id, submitted_by_id, submission_type, payload, submitted_at, late)
                    VALUES (10, 20, 'TEXT', NULL, CURRENT_TIMESTAMP, FALSE)
                    """));
            }
            var script = new ClassPathResource("db/manual/h2-file-submissions.sql");
            ScriptUtils.executeSqlScript(connection, script);
            ScriptUtils.executeSqlScript(connection, script); // Safe to repeat after an interrupted manual run.
            try (var sql = connection.createStatement()) {
                sql.execute("""
                    INSERT INTO submissions (content_id, submitted_by_id, submission_type, payload, submitted_at, late,
                        file_bucket, file_object_key, file_original_filename, file_media_type, file_size_bytes, file_sha256)
                    VALUES (10, 20, 'FILE', NULL, CURRENT_TIMESTAMP, FALSE,
                        'lms-submissions', 'submissions/new-version', 'report.pdf', 'application/pdf', 123,
                        REPEAT('a', 64))
                    """);
                try (var rows = sql.executeQuery("SELECT * FROM submissions ORDER BY id")) {
                    assertTrue(rows.next());
                    assertEquals(1, rows.getLong("id"));
                    assertEquals("TEXT", rows.getString("submission_type"));
                    assertEquals("Original answer", rows.getString("payload"));
                    assertEquals(java.time.Instant.parse("2026-11-15T12:00:00Z"),
                            rows.getObject("submitted_at", java.time.OffsetDateTime.class).toInstant());
                    assertNull(rows.getString("file_bucket"));
                    assertTrue(rows.next());
                    assertEquals(2, rows.getLong("id"));
                    assertEquals("GIT_URL", rows.getString("submission_type"));
                    assertEquals("https://example.com/repo", rows.getString("payload"));
                    assertTrue(rows.getBoolean("late"));
                    assertTrue(rows.next());
                    assertEquals("FILE", rows.getString("submission_type"));
                    assertNull(rows.getString("payload"));
                    assertEquals(123, rows.getLong("file_size_bytes"));
                    assertEquals("a".repeat(64), rows.getString("file_sha256"));
                    assertFalse(rows.next());
                }
            }
        }
    }
}
