-- Manual H2 upgrade; back up the database and stop the app before running.
-- Not run automatically. DDL is not atomic. Does not alter submission history.
CREATE TABLE IF NOT EXISTS grades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT NOT NULL UNIQUE REFERENCES submissions(id),
    score NUMERIC(5, 2) NOT NULL CHECK (score >= 0 AND score <= 100),
    feedback VARCHAR(10000),
    graded_by_id BIGINT NOT NULL REFERENCES enrollments(id),
    graded_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    released_by_id BIGINT REFERENCES enrollments(id),
    released_at TIMESTAMP(6) WITH TIME ZONE,
    version BIGINT NOT NULL,
    CHECK ((released_at IS NULL AND released_by_id IS NULL)
        OR (released_at IS NOT NULL AND released_by_id IS NOT NULL))
);
