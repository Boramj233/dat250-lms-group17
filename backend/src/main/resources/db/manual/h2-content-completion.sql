-- Manual H2 upgrade: back up and stop the application first. Not run automatically.
-- H2 DDL is not atomic. Existing released grades deliberately remain undecided.
ALTER TABLE contents ADD COLUMN IF NOT EXISTS required_for_module_completion BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE quizzes ADD COLUMN IF NOT EXISTS passing_percentage INTEGER DEFAULT 60 NOT NULL CHECK (passing_percentage BETWEEN 1 AND 100);
ALTER TABLE grades ADD COLUMN IF NOT EXISTS passed BOOLEAN;
CREATE TABLE IF NOT EXISTS static_page_completions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_id BIGINT NOT NULL REFERENCES static_pages(id),
    enrollment_id BIGINT NOT NULL REFERENCES enrollments(id),
    completed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    UNIQUE(content_id, enrollment_id)
);
